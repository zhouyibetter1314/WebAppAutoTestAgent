import { test, expect } from '@playwright/test'
test('create application and scenario, run, reload evidence and export', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '添加应用' }).click()
  const fields = page.getByRole('dialog').getByRole('textbox')
  await fields.nth(0).fill('Local fixture')
  await fields.nth(1).fill('http://127.0.0.1:3017')
  await page.getByRole('button', { name: '保存应用' }).click()
  await expect(page.getByText('Local fixture', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新建场景' }).click()
  await page.getByRole('dialog').getByRole('textbox').nth(0).fill('Create project smoke')
  await page
    .getByRole('dialog')
    .getByRole('textbox')
    .nth(1)
    .fill('Create Course Test and verify the result')
  await page.getByRole('button', { name: '保存场景' }).click()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByText('全部检查点已验证', { exact: true })).toBeVisible({ timeout: 30000 })
  await page.reload()
  await expect(page.getByAltText('运行页面截图')).toBeVisible()
  await expect(page.getByText('已满足', { exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载报告包' }).click()
  expect((await download).suggestedFilename()).toMatch(/waat-.*\.zip/)
  await page.screenshot({ path: 'test-results/workbench.png', fullPage: true })
  await page.getByRole('link', { name: '环境与设置' }).click()
  await expect(page.getByText('test-double', { exact: true })).toBeVisible()
})
